import type { Cents } from "./types.ts";

/** A purchasing source. Suppliers are referenced by id, never by name. */
export interface Supplier {
  id: string;
  name: string;
  phone?: string;
}

/** Normalised base unit for one purchasing pack. */
export type BaseUnit = "g" | "ml" | "pcs" | "sheets";

/** One inventory SKU. Supplier ids are independent and may contain any number of sources. */
export interface InventoryItem {
  id: string;
  name: string;
  category: string;
  baseUnit: BaseUnit;
  packQty: number;
  supplierIds: string[];
  workingPriceCents: Cents;
  note?: string;
}

